"""Write BENCHMARKS.md from manifests/*.jsonl and results/check-*.jsonl.

Usage: python3 -m bench.report
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict

from .gen import ROOT


def load(path):
    with path.open() as fh:
        return [json.loads(l) for l in fh]


def _src(pin):
    if pin is None:
        return "none (share only)"
    s = pin["source"]
    if s.startswith("aviary"):
        return "aviary"
    return "avon-copy + mini" if "mini" in s else "avon-copy alone"


def _family_c(rows):
    base = [r for r in rows if r["expect_src"] != "fuel-edge"]
    out = ["Church arithmetic, read back by applying the result to `f x`. `copy` is the",
           "pinned normal-order count (asserted); `share` is Avon's graph-reduction count",
           "(recorded, not asserted). Size is the SKI or BCKW term in leaves.", "",
           "| row | tier | value | size | copy | share | copy / share | pinned by |",
           "|---|---|---:|---:|---:|---:|---:|---|"]
    for r in base:
        val = r["note"].split(";")[0].replace("value ", "")
        copy = r["pin"]["steps"] if r["pin"] else None
        share = r.get("share_ref")
        ratio = f"{copy / share:,.1f}" if copy and share else ""
        note = "" if r["pin"] or ";" not in r["note"] else " (" + r["note"].split("; ", 1)[1] + ")"
        out.append(f"| `{r['id']}` | {r['tier']} | {int(val):,} | {r['size']:,} | "
                   f"{'' if copy is None else f'{copy:,}'} | {'' if share is None else f'{share:,}'} | "
                   f"{ratio} | {_src(r['pin'])}{note} |")
    out.append("")
    return out


def _timing():
    out = []
    for path in sorted((ROOT / "results").glob("timing-*.jsonl")):
        recs = load(path)
        head, recs = recs[0], recs[1:]
        prov = head["provenance"]
        fam = path.stem.split("-", 1)[1]
        out += [f"## Timing, family {fam}", "",
                f"{head['runs']} interleaved runs per engine; CPU = user + sys seconds of the whole",
                "process for Avon (parse, reduce, print), of the reduction alone for mini.",
                f"Avon `{prov['avon_bin'].get('version')}` sha256 `{prov['avon_bin'].get('sha256')}`.",
                "Rate = contractions / median CPU second. Single machine, not a controlled lab.", "",
                "| row | engine | contractions | median CPU s | min CPU s | peak RSS MB | Mcontr/s | wrong |",
                "|---|---|---:|---:|---:|---:|---:|---:|"]
        groups = defaultdict(list)
        for r in recs:
            groups[(r["id"], r["engine"])].append(r)
        import statistics
        for (rid, eng), rs in groups.items():
            good = [r for r in rs if r["ok"]]
            bad = len(rs) - len(good)
            if not good:
                out.append(f"| `{rid}` | {eng} | | | | | | {bad} |")
                continue
            cpus = [r["cpu"] for r in good]
            med = statistics.median(cpus)
            rss = max((r["rss_mb"] or 0) for r in good)
            rate = good[0]["steps"] / med / 1e6 if med else 0
            out.append(f"| `{rid}` | {eng} | {good[0]['steps']:,} | {med:.4f} | {min(cpus):.4f} | "
                       f"{rss:.0f} | {rate:.1f} | {bad} |" if rss else
                       f"| `{rid}` | {eng} | {good[0]['steps']:,} | {med:.4f} | {min(cpus):.4f} | "
                       f"n/a | {rate:.1f} | {bad} |")
        out.append("")
    return out


def main():
    lines = ["# Benchmark results", "",
             "Generated by `python3 -m bench.report` from `manifests/` and `results/`.",
             "Do not edit by hand.", ""]
    for fam in ("A", "B", "C"):
        mpath = ROOT / "manifests" / f"{fam}.jsonl"
        rpath = ROOT / "results" / f"check-{fam}.jsonl"
        if not mpath.exists() or not rpath.exists():
            continue
        rows = load(mpath)
        res = load(rpath)
        prov = res[0]["provenance"]
        res = res[1:]
        lines += [f"## Family {fam}", "",
                  f"{len(rows)} rows ({sum(r['expect_src'] == 'fuel-edge' for r in rows)} of them fuel-edge rows). "
                  f"aviary `{prov['aviary']}`, Avon repo `{prov['avon']}`, "
                  f"binary `{prov['avon_bin'].get('version')}` built {prov['avon_bin'].get('mtime')} "
                  f"(sha256 `{prov['avon_bin'].get('sha256')}`).", "",
                  "| engine | checks | pass | fail |", "|---|---:|---:|---:|"]
        t = Counter((r["engine"], r["ok"]) for r in res)
        for eng in ("aviary", "avon-copy", "avon-share", "mini"):
            p, f = t[(eng, True)], t[(eng, False)]
            if p + f:
                lines.append(f"| {eng} | {p + f} | {p} | {f} |")
        lines.append("")
        if fam == "A":
            share = {r["id"]: r["steps"] for r in res if r["engine"] == "avon-share" and "." in r["id"]}
            diff = [(r["id"], r["pin"]["steps"], share[r["id"]]) for r in rows
                    if r["id"] in share and share[r["id"]] != r["pin"]["steps"]]
            if diff:
                lines += ["Rows where share mode contracts fewer redexes than copy mode:", "",
                          "| row | copy | share |", "|---|---:|---:|"]
                lines += [f"| `{i}` | {c} | {s} |" for i, c, s in diff]
                lines.append("")
        if fam == "B":
            by = defaultdict(dict)
            for r in rows:
                if r["expect_src"] == "fuel-edge":
                    continue
                key = r["id"].rsplit(".", 1)[0][2:]
                by[key][r["basis"]] = (r["size"], r["pin"]["steps"])
            lines += ["Each bird applied to fresh atoms: term size (leaves) / copy-mode contractions",
                      "to normal form, per basis. Sizes include the argument atoms.", "",
                      "| bird | native | SKI | SK | BCKW |", "|---|---:|---:|---:|---:|"]
            tot = Counter()
            for key in sorted(by):
                cells = []
                for b in ("native", "ski", "sk", "bckw"):
                    sz, st = by[key].get(b, (None, None))
                    cells.append("" if sz is None else f"{sz} / {st}")
                    if sz is not None:
                        tot[(b, "size")] += sz
                        tot[(b, "steps")] += st
                lines.append(f"| {key} | " + " | ".join(cells) + " |")
            lines.append("| **total** | " + " | ".join(
                f"**{tot[(b, 'size')]} / {tot[(b, 'steps')]}**" for b in ("native", "ski", "sk", "bckw")) + " |")
            lines.append("")
        if fam == "C":
            lines += _family_c(rows)
    lines += _timing()
    (ROOT / "BENCHMARKS.md").write_text("\n".join(lines))
    print("wrote BENCHMARKS.md")


if __name__ == "__main__":
    main()
